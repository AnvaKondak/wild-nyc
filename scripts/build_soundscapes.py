#!/usr/bin/env python3
"""Build the app's one background sound: calm forest birdsong.

Takes "Birdsong morning 01" by Matutinho (CC BY-SA 4.0, Wikimedia Commons), birdsong
recorded at the edge of a small forest at dawn, and turns it into a soft 75-second loop:
the stretch with the fewest low thuds (the recording has footsteps in it), with the sound
under 900 Hz filtered out so the walking disappears and the birds stay, softened, and
joined end to start so it repeats without a click.

Plain Python (no numpy). Uses macOS afconvert to decode and to encode AAC. Writes
assets/sounds/birds.m4a, src/content/sounds.json (credit) and src/content/soundAssets.ts.

Run from the repo root:  python3 scripts/build_soundscapes.py
"""
import array, json, math, os, statistics, subprocess, urllib.request, wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, "scripts/.sound-cache")
OUT = os.path.join(ROOT, "assets/sounds")
SOURCE = {
    "id": "forest-birdsong",
    "url": "https://upload.wikimedia.org/wikipedia/commons/transcoded/e/e7/Birdsong_morning_01.ogg/Birdsong_morning_01.ogg.mp3",
    "credit": {
        "title": "Birdsong morning 01",
        "license": "CC BY-SA 4.0",
        "artist": "Matutinho",
        "source": "https://commons.wikimedia.org/wiki/File:Birdsong_morning_01.ogg",
    },
}
SR = 22050
LOOP = 75  # seconds
XFADE = 4  # seconds folded from the end over the start, so the loop has no seam
CUT = 900  # Hz: everything below is filtered out (footsteps, handling, wind rumble)


def decode(path):
    """Stereo 16-bit samples at SR, via afconvert (its WAV header is read by hand)."""
    tmp = path + ".wav"
    subprocess.run(["afconvert", "-f", "WAVE", "-d", f"LEI16@{SR}", "-c", "2", path, tmp], check=True)
    raw = open(tmp, "rb").read()
    os.remove(tmp)
    i = 12
    while raw[i:i + 4] != b"data":
        i += 8 + int.from_bytes(raw[i + 4:i + 8], "little")
    size = int.from_bytes(raw[i + 4:i + 8], "little")
    a = array.array("h", raw[i + 8:i + 8 + size - size % 4])
    return list(a[0::2]), list(a[1::2])


def lowpass(xs, fc):
    k, y, out = 1 - math.exp(-2 * math.pi * fc / SR), 0.0, []
    for x in xs:
        y += k * (x - y)
        out.append(y)
    return out


def highpass(xs, fc):
    return [x - l for x, l in zip(xs, lowpass(xs, fc))]


def quietest_start(left, right):
    """Where the 79 seconds with the fewest low thuds (footsteps) begin, in samples."""
    low = lowpass([(l + r) / 2 for l, r in zip(left, right)], 250)
    step = SR // 4
    level = [math.sqrt(sum(v * v for v in low[j:j + step:2]) / (step / 2)) for j in range(0, len(low) - step, step)]
    med = statistics.median(level)
    span = (LOOP + XFADE) * 4
    score = lambda s: sum(max(0, x - 1.8 * med) for x in level[s:s + span]) / med + statistics.mean(level[s:s + span]) / med
    return min(range(0, len(level) - span, 4), key=score) * step


def main():
    os.makedirs(CACHE, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    src = os.path.join(CACHE, f"{SOURCE['id']}.mp3")
    if not os.path.exists(src):
        req = urllib.request.Request(SOURCE["url"], headers={"User-Agent": "WildNeighbors/0.1 (bundling a CC BY-SA sound)"})
        open(src, "wb").write(urllib.request.urlopen(req, timeout=120).read())
    left, right = decode(src)
    start, total, n, x = quietest_start(left, right), (LOOP + XFADE) * SR, LOOP * SR, XFADE * SR
    channels = []
    for ch in (left, right):
        seg = highpass(highpass(ch[start:start + total], CUT), CUT)  # twice, for a steeper cut
        loop = seg[:n]
        for j in range(x):  # equal-power crossfade of the tail over the head
            g = math.pi / 2 * j / x
            loop[j] = loop[j] * math.sin(g) + seg[n + j] * math.cos(g)
        channels.append(loop)
    peak = max(1, max(abs(v) for ch in channels for v in ch))
    gain = 0.55 * 32767 / peak
    pcm = array.array("h", (int(max(-32767, min(32767, v * gain))) for pair in zip(*channels) for v in pair))
    tmp = os.path.join(CACHE, "birds.mix.wav")
    with wave.open(tmp, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", "96000", tmp, os.path.join(OUT, "birds.m4a")], check=True)
    os.remove(tmp)
    json.dump(
        {"loops": {"birds": [SOURCE["id"]]}, "recordings": {SOURCE["id"]: SOURCE["credit"]}},
        open(os.path.join(ROOT, "src/content/sounds.json"), "w"),
        indent=2,
        ensure_ascii=False,
    )
    open(os.path.join(ROOT, "src/content/soundAssets.ts"), "w").write(
        "// Generated by scripts/build_soundscapes.py. Do not edit by hand.\n\n"
        "export const soundAssets: Record<string, number> = {\n  'birds': require('../../assets/sounds/birds.m4a'),\n};\n"
    )
    print(f"birds.m4a: {LOOP} s from {start // SR} s into the recording, lows under {CUT} Hz cut")


if __name__ == "__main__":
    main()
